def get_p(start_p, end_p):
    parts = []
    for p in range(start_p, min(end_p + 1, len(pages))):
        lines = pages[p].split('\n', 1)
        body = lines[1] if len(lines) > 1 else ''
        parts.append(body.strip())
    return '\n\n'.join(parts)

def clean_text(t):
    # Name replacements
    t = re.sub(r'ماورا', 'رجاء', t)
    t = re.sub(r'انعم', 'رجاء', t)
    t = re.sub(r'انم\b', 'رجاء', t)
    
    # OCR and layout fixes
    artefacts = {
        'یہحصہ': 'یہ حصہ',
        'کھماؤں کے د': 'ماؤں کے دکھ',
        'پرفنےکس': 'پرفیکٹ',
        'پرفنےکٹ': 'پرفیکٹ',
        'پرف نےکٹ': 'پرفیکٹ',
        'ئیاپنوں': 'اپنوں',
        'کیلڑ ہلناا': 'لڑکی کا لڑنا',
        'لےمحلے وا': 'محلے والے',
        'نہپیما': 'پیمانہ',
        'ستیقرآن': 'قرآن',
        'ستیحاسد': 'حاسد کی دوستی',
        'ئیںجا جب دونوں ٹکرا': 'جب دونوں ٹکرا جائیں',
        'یںاپنوں': 'اپنوں',
        'یںجب اپنے': 'جب اپنے',
        'نہبہا': 'بہانہ',
        'بیتی ماورا': 'بیتی رجاء',
        'خنزیر سے زیاده غلیظ': 'انتہائی تلخ اور زہریلا'
    }
    for k, v in artefacts.items():
        t = t.replace(k, v)
    return t

