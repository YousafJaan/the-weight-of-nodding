# Add Table of Contents in docx
p_toc = doc.add_paragraph()
p_toc.alignment = WD_ALIGN_PARAGRAPH.RIGHT
p_toc.add_run('فہرستِ ابواب:\n').bold = True
for i in range(1, 12):
    t, _ = chapters[i]
    p_toc.add_run(f'{t}\n')

doc.add_page_break()

# Add Chapters
for i in range(1, 12):
    title, body = chapters[i]
    p_ch = doc.add_paragraph()
    p_ch.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    run_ch = p_ch.add_run(f'\n{title}\n')
    run_ch.font.name = 'Jameel Noori Nastaleeq'
    run_ch.font.size = Pt(18)
    run_ch.bold = True
    run_ch.font.color.rgb = RGBColor(140, 29, 64)
    
    # Paragraphs
    for para in body.split('\n\n'):
        para_s = para.strip()
        if not para_s: continue
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        run_p = p.add_run(para_s)
        run_p.font.size = Pt(12)
    
    if i < 11:
        doc.add_page_break()

